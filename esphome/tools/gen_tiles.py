#!/usr/bin/env python3
"""Generate esphome/tiles/tile_NN.yaml from tiles.csv (id,q,r[,rot]).

Usage: python3 tools/gen_tiles.py [tiles.csv]
tile_num (1..N, CSV order) is the hexsync id and default leader priority,
so the first row (the centre tile) is the preferred leader.
"""
import csv, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent.parent
src = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here / "tiles.csv"
out = here / "tiles"
out.mkdir(exist_ok=True)
rows = list(csv.DictReader(open(src)))
seen = set()
for n, row in enumerate(rows, 1):
    tid = re.sub(r"[^a-z0-9-]", "-", row["id"].strip().lower())
    q, r = int(row["q"]), int(row["r"])
    if (q, r) in seen:
        sys.exit(f"duplicate position q={q} r={r}")
    seen.add((q, r))
    rot = int(row.get("rot") or 0)
    (out / f"tile_{n:02d}.yaml").write_text(
        f"""# GENERATED by tools/gen_tiles.py from {src.name}; edit the CSV, not this file.
substitutions:
  tile_id: "{tid}"
  tile_num: "{n}"
  q: "{q}"
  r: "{r}"
  rotation: "{rot}"

packages:
  tile: !include ../templates/tile-common.yaml
"""
    )
print(f"wrote {len(rows)} tiles to {out}")
